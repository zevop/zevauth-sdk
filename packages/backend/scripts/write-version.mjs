// Keeps src/version.ts in step with package.json, so the user agent the
// API client sends always names the version that was actually built.
import { readFileSync, writeFileSync } from 'node:fs';
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
  new URL('../src/version.ts', import.meta.url),
  `// Generated by scripts/write-version.mjs from package.json at build time.\n// Do not edit by hand.\nexport const VERSION = '${version}';\n`,
);
